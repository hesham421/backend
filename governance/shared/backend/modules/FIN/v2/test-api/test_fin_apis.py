def preflight(c: APIClient):
    """Stage A0 — every externally-owned value the payloads reference is verified present
    and active through MDL's own documented read endpoint before any suite runs.
    Order is grants -> preconditions -> suites; this run needs no grant (see grants())."""
    start_suite("PREFLIGHT (stage A0)")

    def check(key, wanted):
        def _fn():
            r = c.get("/api/v1/mdl/lookups", params={"type": key})
            vals = data_of(r) or []
            codes = [v.get("code") for v in vals] if isinstance(vals, list) else []
            missing = [w for w in wanted if w not in codes]
            if missing:
                PRECONDITION_FAILURES.append(
                    f"{key}: missing active value(s) {missing} — api-docs examples reference them")
            return (not missing,
                    f"{key}: {len(codes)} active value(s); missing={missing or 'none'}",
                    ",".join(str(x) for x in codes))
        return _fn

    for key, wanted in REQUIRED_LOOKUPS.items():
        run(f"MDL lookup '{key}' present and active (XM-FIN-001)", check(key, wanted))

    def direct_is_retired():
        """db-script v2 BLOCK 8 deactivates DIRECT in ACCOUNT_DERIVATION_TYPE — the
        precondition TC-FIN-094 names explicitly."""
        r = c.get("/api/v1/mdl/lookups", params={"type": "ACCOUNT_DERIVATION_TYPE"})
        codes = [v.get("code") for v in (data_of(r) or [])]
        return ("DIRECT" not in codes,
                f"active ACCOUNT_DERIVATION_TYPE values = {codes} (DIRECT must be absent, "
                f"db-script v2 BLOCK 8)", snippet(r))

    run("precondition — DIRECT is no longer an active ACCOUNT_DERIVATION_TYPE (BLOCK 8)",
        direct_is_retired)

    def seed_event_type():
        """The host-specific step the manifest documents (DEPENDENCY ORDER step 0): an
        ACCOUNTING_EVENT_TYPE value must exist in MDL before a rule can name it."""
        r = c.post("/api/v1/mdl/lookup-types/search",
                   {"filters": [{"field": "key", "operator": "EQUALS",
                                 "value": "ACCOUNTING_EVENT_TYPE"}],
                    "page": 0, "size": 5})
        content = [t for t in ((data_of(r) or {}).get("content") or [])
                   if t.get("key") == "ACCOUNTING_EVENT_TYPE"]
        if not content:
            PRECONDITION_FAILURES.append(
                "ACCOUNTING_EVENT_TYPE lookup type not found via MDL search — "
                "every event suite is blocked")
            return False, "lookup type ACCOUNTING_EVENT_TYPE not found", snippet(r)
        ctx["event_type_lookup_id"] = content[0].get("lookupTypePk") or content[0].get("id")
        code = seed_event_type_value(c, "BASE")
        if not code:
            PRECONDITION_FAILURES.append("could not seed an ACCOUNTING_EVENT_TYPE value")
            return False, "seed failed", ""
        ctx["event_type_code"] = code
        return True, f"seeded ACCOUNTING_EVENT_TYPE value {code}", ""

    run("precondition — seed a host-specific ACCOUNTING_EVENT_TYPE value "
        "(manifest DEPENDENCY ORDER step 0)", seed_event_type)

    def seed_transfer_payment_method():
        """Host data the manifest's DEPENDENCY ORDER step 0 names in as many words:
        "every PAYMENT_METHOD value but CHEQUE (CASH, TRANSFER) are added in MDL by the
        deploying organisation". TC-FIN-105's precondition needs TRANSFER present, because
        RULE-FIN-024 refuses a mapping on a PAYMENT_METHOD value MDL does not hold, and
        without that mapping the case cannot demonstrate that the inactive row is excluded."""
        r = c.get("/api/v1/mdl/lookups", params={"type": "PAYMENT_METHOD"})
        codes = [v.get("code") for v in (data_of(r) or [])]
        if "TRANSFER" in codes:
            return True, "TRANSFER already present as active host data", ""
        s = c.post("/api/v1/mdl/lookup-types/search",
                   {"filters": [{"field": "key", "operator": "EQUALS",
                                 "value": "PAYMENT_METHOD"}], "page": 0, "size": 5})
        hits = [t for t in ((data_of(s) or {}).get("content") or [])
                if t.get("key") == "PAYMENT_METHOD"]
        if not hits:
            PRECONDITION_FAILURES.append("PAYMENT_METHOD lookup type not found in MDL")
            return False, "PAYMENT_METHOD lookup type not found", snippet(s)
        tid = hits[0].get("lookupTypePk") or hits[0].get("id")
        cr = c.post(f"/api/v1/mdl/lookup-types/{tid}/values",
                    {"code": "TRANSFER", "nameAr": "تحويل", "nameEn": "Transfer",
                     "sortOrder": 3})
        if cr.status_code in (200, 201):
            # Deliberately NOT appended to created["MdlLookupValue"]: this is the host
            # reference data the manifest says the deploying organisation provides, not
            # run-scoped residue. Retiring it would leave the environment one host value
            # poorer, and MDL publishes no way to reactivate a retired lookup value.
            ctx["transfer_payment_method_active"] = True
            return True, (f"seeded the host PAYMENT_METHOD value TRANSFER "
                          f"(id={field_of(cr, 'lookupValuePk')}); left in place as host "
                          f"data, not torn down"), ""
        if err_code(cr) == "MDL-409-VALUE-DUP":
            # The code exists but is INACTIVE, and MDL publishes no activate endpoint for a
            # lookup value (LookupValueController: create / update{nameAr,nameEn,sortOrder}
            # / DELETE=deactivate / reorder / search). Reactivating it would be a data fix
            # against a row this run did not create, which SKILL.md §3-H says is emitted as
            # suggested SQL for a human and never executed.
            ctx["transfer_payment_method_active"] = False
            PRECONDITION_FAILURES.append(
                "PAYMENT_METHOD value TRANSFER exists but is INACTIVE in MDL, and MDL "
                "publishes no activate endpoint for a lookup value. TC-FIN-105's literal "
                "fixture (an inactive TRANSFER mapping) cannot be built; the case falls "
                "back to an EXPENSE_TYPE_CODE-keyed inactive third row, which demonstrates "
                "the same exclusion. Suggested SQL for a human, NOT executed: "
                "UPDATE MDL_LOOKUP_VALUE SET IS_ACTIVE_FL = TRUE WHERE CODE = 'TRANSFER' "
                "AND LOOKUP_TYPE_ID = (SELECT LOOKUP_TYPE_PK FROM MDL_LOOKUP_TYPE WHERE "
                "KEY = 'PAYMENT_METHOD');")
            return (True,
                    "TRANSFER present but INACTIVE — recorded as a precondition note with "
                    "suggested SQL; TC-FIN-105 uses its documented fallback key", snippet(cr))
        PRECONDITION_FAILURES.append(
            f"could not add the host PAYMENT_METHOD value TRANSFER: HTTP {cr.status_code} "
            f"{err_code(cr)}")
        return False, f"HTTP {cr.status_code} {err_code(cr)}", snippet(cr)

    run("precondition — the host PAYMENT_METHOD value TRANSFER (manifest DEPENDENCY ORDER "
        "step 0), required by TC-FIN-105", seed_transfer_payment_method)


