def test_registration(c: APIClient):
    """Covers: TC-FIN-044 (SEC registration), TC-FIN-045 (MDL lookup types)
    Reads SEC's own POST /api/v1/sec/registry/search and MDL's by-owner search."""
    start_suite("Registration (SEC + MDL)")

    def sec_registration():
        r = c.post("/api/v1/sec/registry/search", {"page": 0, "size": 200})
        content = (data_of(r) or {}).get("content") or []
        fin = [m for m in content if m.get("code") == "FIN"]
        if not fin:
            return False, "module FIN is not registered in SEC_MODULE_REG", snippet(r)
        screens = fin[0].get("screens") or []
        actions = [a for s in screens for a in (s.get("actions") or [])]
        ctx["sec_screens"] = sorted(s.get("pageCode") for s in screens)
        ctx["sec_actions"] = sorted(a.get("permissionCode") for a in actions)
        return (len(screens) == 13 and len(actions) == 30,
                f"FIN registered with {len(screens)} screen(s) and {len(actions)} action(s) "
                f"(v2 SCREEN REGISTRY declares 13 and 30)",
                ",".join(ctx["sec_screens"]))

    run("TC-FIN-044 — FIN registers itself into SEC as data (13 screens / 30 actions)",
        sec_registration)

    def mapping_screen_registered():
        return (("FIN_ACCOUNT_MAPPINGS" in (ctx.get("sec_screens") or [])
                 and all(p in (ctx.get("sec_actions") or [])
                         for p in ("PERM_FIN_ACCOUNT_MAPPINGS_VIEW",
                                   "PERM_FIN_ACCOUNT_MAPPINGS_CREATE",
                                   "PERM_FIN_ACCOUNT_MAPPINGS_UPDATE"))),
                "v2's SCR-REQ-FIN-013 screen and its three actions are registered", "")

    run("TC-FIN-044b — the v2 FIN_ACCOUNT_MAPPINGS screen and its three actions are "
        "registered (V37)", mapping_screen_registered)

    def mdl_lookup_types():
        r = c.post("/api/v1/mdl/lookup-types/by-owner/search", {"page": 0, "size": 200})
        groups = data_of(r) or []
        fin = [g for g in groups if g.get("ownerModuleCode") == "FIN"]
        types = (fin[0].get("types") or []) if fin else []
        keys = sorted(t.get("key", "") for t in types)
        return (len(types) == 15,
                f"FIN-owned lookup types = {len(types)} (REQ-FIN-045 registers 15 in v2: "
                f"the 13 v1 keys plus FIN_EVENT_BUSINESS_FIELD and FIN_DIMENSION_VALUE_SOURCE)",
                ",".join(keys)[:280])

    run("TC-FIN-045 — FIN registers its fifteen lookup types into MDL", mdl_lookup_types)


