def main() -> int:
    global BASE_URL
    if len(sys.argv) > 1:
        BASE_URL = sys.argv[1].rstrip("/")

    c = APIClient(BASE_URL)
    print(f"api-verify — FIN v2 · tier Full · RUN_ID={RUN_ID} · target {BASE_URL}")

    tok = c.login(ADMIN_USERNAME, ADMIN_PASSWORD)
    if not tok:
        print("FATAL: could not authenticate — ENVIRONMENT_FAILURE", file=sys.stderr)
        return 2
    c.token = tok

    try:
        grants(c)
        preflight(c)
        test_registration(c)
        test_dimension(c)
        test_account(c)
        test_fiscal_year(c)
        test_fiscal_period(c)
        test_dimension_value(c)
        test_account_mapping(c)
        test_event_rule(c)
        test_journal_entry(c)
        test_reversal(c)
        test_event_entry(c)
        test_event_mapping(c)
        test_event_dimension_tags(c)
        test_event_distribution(c)
        test_recurring_template(c)
        test_allocation_rule(c)
        # The year-end close runs BEFORE the reports suite: TC-FIN-042 asserts the income
        # statement of the year that follows a year genuinely year-end-closed, so that
        # close must already have happened. It operates on its own far-future adjacent
        # year pair and touches none of the fixtures the other suites use.
        test_year_end_close(c)
        test_reports(c)
        test_published_catalogue(c)
        test_permission_gate(c)
    finally:
        try:
            cleanup(c)
        except Exception as e:  # noqa: BLE001
            print(f"cleanup FAILED: {e}")
        write_report(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                  "fin_problems_report.md"))

    total_f = sum(s.failed_count for s in SUITES)
    print(f"\nTOTAL: {sum(s.passed_count for s in SUITES)} passed, {total_f} failed")
    return 1 if total_f else 0


if __name__ == "__main__":
    raise SystemExit(main())
