def _event(ref, evt, doc_date, amount=1000.0, fields=None, amounts=None):
    body = {"eventReference": ref, "eventTypeCode": evt, "docDate": doc_date,
            "baseAmount": amount, "descriptionAr": "حدث", "descriptionEn": "Event"}
    if fields is not None:
        body["fields"] = fields
    body["amounts"] = amounts if amounts is not None else {"netAmount": amount}
    return body


