    def trial_balance_balances():
        """TC-FIN-040 / AC-FIN-040 — **total debit balances equal total credit balances**.
        The api-docs publish exactly those two columns on TrialBalanceResponse —
        totalDebitBalance, totalCreditBalance — plus `balanced`, "whether the two column
        totals match, an invariant by construction (POL-FIN-008)". rows[].debitTotal /
        creditTotal are the *line* sums, a different quantity, and are not what this AC is
        about. A rows > 0 guard keeps 0 == 0 from passing vacuously.
        Step 1: with periodId. Step 2: with periodId omitted."""
        out = []
        ok_all = True
        for label, params in (("with periodId", {"periodId": ctx.get("period2_id")}),
                              ("periodId omitted", None)):
            r = c.get("/api/v1/fin/reports/trial-balance", params=params)
