def test_year_end_close(c: APIClient):
    """Covers: API-FIN-027 ; TC-FIN-036"""
    start_suite("FiscalYear year-end close")

    def make_adjacent_pair():
        """The manifest's TC-FIN-036 precondition: the year being closed needs a SUCCESSOR
        year whose startDate is the day after its endDate (the adjacency is derived —
        ENT-FIN-007 declares no successor column)."""
        for y in range(FY_YEAR + 10, FY_YEAR + 60):
            a = c.post("/api/v1/fin/fiscal-years",
                       {"code": str(y), "startDate": f"{y}-01-01",
                        "endDate": f"{y}-12-31", "periodCount": 12})
            if err_code(a) == "FIN-409-YEAR-DUP":
                continue
            if a.status_code not in (200, 201):
                return False, f"year {y} HTTP {a.status_code} {err_code(a)}", snippet(a)
            b = c.post("/api/v1/fin/fiscal-years",
                       {"code": str(y + 1), "startDate": f"{y + 1}-01-01",
                        "endDate": f"{y + 1}-12-31", "periodCount": 12})
            if err_code(b) == "FIN-409-YEAR-DUP":
                # y is free but y+1 was taken by an earlier run; keep walking rather than
                # declaring the whole case unrunnable.
                created["FiscalYear"].append(field_of(a, "fiscalYearPk"))
                continue
            if b.status_code not in (200, 201):
                return False, f"successor {y + 1} HTTP {b.status_code} {err_code(b)}", snippet(b)
            ctx["close_year_id"] = field_of(a, "fiscalYearPk")
            ctx["close_successor_id"] = field_of(b, "fiscalYearPk")
            created["FiscalYear"].extend([ctx["close_year_id"], ctx["close_successor_id"]])
            for resp in (a, b):
                created["FiscalPeriod"].extend(
                    p.get("fiscalPeriodPk") for p in (field_of(resp, "periods") or []))
            return True, f"years {y} (id={ctx['close_year_id']}) and {y + 1} " \
                         f"(id={ctx['close_successor_id']}) created adjacent", ""
        return False, "no free adjacent year pair", ""

    run("setup — an adjacent year pair for the year-end close (API-FIN-023)",
        make_adjacent_pair)

    fy = ctx.get("close_year_id")
    if not fy:
        blocked("TC-FIN-036", "no closable fiscal year pair")
        return

    def close_year():
        """AC-FIN-036 — every period hard-closed first, then the close posts a balanced
        closing entry and the next year's opening entry; the RULE-FIN-008 carve-out means
        the closed periods do NOT refuse them."""
        sr = c.post("/api/v1/fin/fiscal-periods/search",
                    {"page": 0, "size": 50,
                     "filters": [{"field": "fiscalYearId", "operator": "EQUALS",
                                  "value": fy}]})
        ps = (data_of(sr) or {}).get("content") or []
        if not ps:
            return False, "the year under close has no periods", snippet(sr)
        # Real activity first: AC-FIN-036's closing entry closes RESULT accounts to
        # Retained Earnings, so a year with nothing posted produces two empty entries and
        # "each is individually balanced" would hold vacuously (that empty shape is a
        # different case). One balanced EXPENSE/REVENUE entry is posted into the year's
        # first period before every period is hard-closed.
        seed = c.post("/api/v1/fin/journal-entries",
                      _entry_body(ps[0].get("fiscalPeriodPk"), ps[0].get("startDate"),
                                  [{"accountId": ctx["expense_account_id"], "amount": 640.0,
                                    "directionCode": "DEBIT"},
                                   {"accountId": ctx["revenue_account_id"], "amount": 640.0,
                                    "directionCode": "CREDIT"}],
                                  fy=fy))
        if seed.status_code not in (200, 201):
            return (False,
                    f"could not post activity into the year under close — HTTP "
                    f"{seed.status_code} {err_code(seed)}", snippet(seed))
        created["JournalEntry"].append(field_of(seed, "journalEntryPk"))
        for p in ps:
            pid = p.get("fiscalPeriodPk")
            c.patch(f"/api/v1/fin/fiscal-periods/{pid}/soft-close")
            c.patch(f"/api/v1/fin/fiscal-periods/{pid}/hard-close")
        r = c.post(f"/api/v1/fin/fiscal-years/{fy}/year-end-close")
        if r.status_code not in (200, 201):
            return False, f"HTTP {r.status_code} {err_code(r)}", snippet(r)
        d = data_of(r)
        if not isinstance(d, dict):
            return False, f"unexpected payload type {type(d).__name__}", snippet(r)
        # API-FIN-027 serves YearEndCloseResponse — NOT FiscalYearResponse — and it carries
        # BOTH entries: `closingEntry | JournalEntryResponse` and
        # `openingEntry | JournalEntryResponse` (api-docs endpoints/
        # fin-fiscal-year-management.md, "Shape: YearEndCloseResponse"; controller
        # FiscalYearController.yearEndClose -> ResponseEntity<ApiResponse<YearEndCloseResponse>>).
        closing, opening = d.get("closingEntry"), d.get("openingEntry")
        for e in (closing, opening):
            if isinstance(e, dict) and e.get("journalEntryPk"):
                created["JournalEntry"].append(e["journalEntryPk"])

        def balanced(e):
            if not isinstance(e, dict):
                return False, None, None
            ls = e.get("lines") or []
            deb = sum(float(l.get("amount") or 0) for l in ls
                      if l.get("directionCode") == "DEBIT")
            cre = sum(float(l.get("amount") or 0) for l in ls
                      if l.get("directionCode") == "CREDIT")
            return abs(deb - cre) < 0.005, deb, cre

        cb, cd, cc = balanced(closing)
        ob, od, oc = balanced(opening)
        both_present = isinstance(closing, dict) and isinstance(opening, dict)
        posted = both_present and closing.get("statusCode") == "POSTED" \
            and opening.get("statusCode") == "POSTED"
        # the close must have MOVED something: with activity posted above, an empty
        # closing entry would mean the result accounts were never closed to Retained
        # Earnings, and "balanced" would be true of nothing at all.
        moved = both_present and (closing.get("lines") or []) and cd > 0
        return (both_present and cb and ob and posted and moved,
                f"HTTP {r.status_code} · closingEntry present={isinstance(closing, dict)} "
                f"(id={(closing or {}).get('journalEntryPk')}, debits={cd}, credits={cc}, "
                f"balanced={cb}) · openingEntry present={isinstance(opening, dict)} "
                f"(id={(opening or {}).get('journalEntryPk')}, debits={od}, credits={oc}, "
                f"balanced={ob}) · the closing entry actually moved the year's result "
                f"balances={bool(moved)} ({len((closing or {}).get('lines') or [])} line(s)) "
                f"· both POSTED={posted} · FIN-409-PERIOD-NOT-OPEN not "
                f"raised over the hard-closed periods (RULE-FIN-008's own carve-out)",
                snippet(r))

    run("TC-FIN-036 — year-end close returns BOTH entries and each individually balances "
        "(API-FIN-027, YearEndCloseResponse)", close_year)


def test_published_catalogue(c: APIClient):
    """TC-FIN-127 — a property of the published api-docs catalogue itself, not of an
    endpoint: the period-not-open code is documented exactly once."""
    start_suite("Published catalogue")

    def documented_once():
        """TC-FIN-127 / AC-FIN-081 — the catalogue lists FIN-409-PERIOD-NOT-OPEN **exactly
        once**, WITH its ar/en message and WITH the note that the rejection clears once the
        target period is opened. All four are asserted: the once-only clause alone was
        never what AC-FIN-081 asks for."""
        try:
            text = open(API_DOCS_INDEX, encoding="utf-8").read()
        except OSError as e:
            return False, f"could not read {API_DOCS_INDEX}: {e}", ""
        rows = [l for l in text.splitlines()
                if l.startswith("| FIN_409_PERIOD_NOT_OPEN ")]
        if len(rows) != 1:
            return (False,
                    f"Known Error Codes rows for FIN-409-PERIOD-NOT-OPEN: {len(rows)} "
                    f"(want exactly 1)", " || ".join(r[:150] for r in rows))
        row = rows[0]
        checks = {
            "value FIN-409-PERIOD-NOT-OPEN": "`FIN-409-PERIOD-NOT-OPEN`" in row,
            "en message": "The target period is not open" in row,
            "ar message": "الفترة المستهدفة غير مفتوحة" in row,
            "HTTP 409 CONFLICT": "409 CONFLICT" in row,
            "clearing note": ("Retryable" in row
                              and "clears once the target period is opened" in row),
        }
        missing = [k for k, v in checks.items() if not v]
        return (not missing,
                f"exactly 1 catalogue row; present: "
                f"{[k for k, v in checks.items() if v]}; missing: {missing or 'none'}",
                row[:300])

    run("TC-FIN-127 — the published catalogue documents the period-not-open code exactly "
        "once, with both messages, its 409 and the clearing note (AC-FIN-081)",
        documented_once)


def test_permission_gate(c: APIClient):
    """TC-FIN-038 and TC-FIN-052 — entry-creation permission alone does not buy a period
    close, and the same permission gates the year-end close.

    Both need a principal that does NOT hold PERM_FIN_PERIODS_CLOSE_APPROVE. The run's own
    account is the bootstrap SYS_ADMIN, which the FIN security migrations grant it to, and
    minting a SEC user and role is outside the single bounded exception of SKILL.md §3-I.
    So api-verify does not cover them, and says so rather than approximating them.

    They ARE covered, at the denial itself, in the JUnit track:
      TC-FIN-038 → FinSoDCoverageIntegrationTest
                   #hardClose_isDeniedForAPrincipalHoldingOnlyTheEntryCreationPermission
      TC-FIN-052 → FinSoDCoverageIntegrationTest
                   #yearEndClose_isDeniedForAPrincipalHoldingOnlyTheEntryCreationPermission
    """
    start_suite("Permission gate (RULE-FIN-015)")
    skipped("TC-FIN-038 — entry-creation permission alone does not buy a period close",
            "not exercisable by api-verify (needs a principal WITHOUT "
            "PERM_FIN_PERIODS_CLOSE_APPROVE; minting a SEC user/role is outside SKILL.md "
            "§3-I). COVERED in the JUnit track: FinSoDCoverageIntegrationTest"
            "#hardClose_isDeniedForAPrincipalHoldingOnlyTheEntryCreationPermission")
    skipped("TC-FIN-052 — the same permission gates the year-end close",
            "same reason as TC-FIN-038. COVERED in the JUnit track: "
            "FinSoDCoverageIntegrationTest"
            "#yearEndClose_isDeniedForAPrincipalHoldingOnlyTheEntryCreationPermission")


