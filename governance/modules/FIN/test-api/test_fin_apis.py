def cleanup(c: APIClient):
    """Reverse of the manifest's DEPENDENCY ORDER. FIN documents NO hard-delete endpoint
    for any entity, so every call below is the documented soft deactivate and the rows
    survive — listed individually in the report, never summarised as 'cleaned up'."""
    print("\n=== CLEANUP (reverse dependency order) ===")

    if created["JournalEntry"]:
        LEFT_BEHIND.append(
            f"JournalEntry: {len([i for i in created['JournalEntry'] if i])} entr(ies) "
            f"{[i for i in created['JournalEntry'] if i]} — immutable by design "
            "(RULE-FIN-016, no delete or void route); left behind POSTED.")

    for label, path in (
        ("AllocationRule", "/api/v1/fin/allocation-rules/{id}/deactivate"),
        ("DimensionValue", "/api/v1/fin/dimensions/values/{id}/deactivate"),
        ("RecurringTemplate", "/api/v1/fin/recurring-templates/{id}/deactivate"),
        ("EventTypeRule", "/api/v1/fin/event-rules/{id}/deactivate"),
        ("Account", "/api/v1/fin/accounts/{id}/deactivate"),
    ):
        for _id in [i for i in created[label] if i]:
            try:
                r = c.put(path.format(id=_id))
                print(f"  deactivate {label} {_id}: {r.status_code}")
            except Exception as e:  # noqa: BLE001
                print(f"  deactivate {label} {_id} FAILED: {e}")
        if created[label]:
            LEFT_BEHIND.append(
                f"{label}: {[i for i in created[label] if i]} — deactivated (soft); "
                "FIN documents no hard delete.")

    if created["FiscalPeriod"] or created["FiscalYear"]:
        LEFT_BEHIND.append(
            f"FiscalYear {created['FiscalYear']} and its "
            f"{len(created['FiscalPeriod'])} period(s) — no deactivate or delete endpoint "
            "exists (ENTITY CRUD CHECKLIST: FiscalYear's only retirement is year-end close); "
            "left behind.")

    if created["Dimension"]:
        LEFT_BEHIND.append(
            f"Dimension: {created['Dimension']} — no deactivate endpoint exists "
            "(ENTITY CRUD CHECKLIST ENT-FIN-002 shows '—'); left behind ACTIVE.")

    # Permanent residue: a row in MDL's reference table, which other modules' rules read.
    for vid in [i for i in created["MdlLookupValue"] if i]:
        try:
            r = c.delete(f"/api/v1/mdl/lookup-values/{vid}")
            print(f"  retire MDL lookup value {vid}: {r.status_code}")
            PERMANENT_RESIDUE.append(
                f"MDL lookup value {vid} (ACCOUNTING_EVENT_TYPE / "
                f"{ctx.get('event_type_code')}) — retired via "
                f"DELETE /api/v1/mdl/lookup-values/{vid} -> HTTP {r.status_code}. "
                f"Cleanup SQL if it is still active: "
                f"UPDATE MDL_LOOKUP_VALUE SET IS_ACTIVE_FL = FALSE "
                f"WHERE LOOKUP_VALUE_PK = {vid};")
        except Exception as e:  # noqa: BLE001
            PERMANENT_RESIDUE.append(f"MDL lookup value {vid} — retire FAILED: {e}")


