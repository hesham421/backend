def preflight(c: APIClient):
    """Stage A0 — every externally-owned value the payloads reference is verified
    present and active through MDL's own documented read endpoint before any suite.
    Order is grants -> preconditions -> suites; this run needs no grant (see grants())."""
    start_suite("PREFLIGHT (stage A0)")

    lookup_values: dict[str, list[str]] = {}

    def check(key, wanted):
        def _fn():
            r = c.get("/api/v1/mdl/lookups", params={"type": key})
            vals = data_of(r) or []
            codes = [v.get("code") for v in vals] if isinstance(vals, list) else []
            lookup_values[key] = codes
            missing = [w for w in wanted if w not in codes]
            if missing:
                PRECONDITION_FAILURES.append(
                    f"{key}: missing active value(s) {missing} — api-docs examples reference them")
            return (not missing,
                    f"{key}: {len(codes)} active value(s); missing={missing or 'none'}",
                    ",".join(codes))
        return _fn

    for key, wanted in REQUIRED_LOOKUPS.items():
        run(f"MDL lookup '{key}' present and active (XM-FIN-001)", check(key, wanted))

    # TC-FIN-045 / TC-FIN-090 — FIN registers 13 lookup types into MDL at onboarding,
    # two of them deliberately empty (V26__fin_mdl_lookup_seed.sql lines 48-61).
    def event_type_seeded():
        r = c.get("/api/v1/mdl/lookups", params={"type": "ACCOUNTING_EVENT_TYPE"})
        vals = data_of(r) or []
        return (r.status_code == 200,
                f"ACCOUNTING_EVENT_TYPE resolves with {len(vals)} value(s) "
                f"(V26 documents zero-by-design: host-specific)", snippet(r))

    run("TC-FIN-090 — ACCOUNTING_EVENT_TYPE registered but deliberately empty", event_type_seeded)

    # The host-specific step V26 documents: an event type must be added through MDL's
    # lookup administration before an event-type rule can be created. This is the
    # documented step, not an invented value.
    def seed_event_type():
        # MDL's LookupTypeSearchRequest filters on `key` (LookupTypeSearchRequest javadoc);
        # `code` is NOT a filterable field and is silently ignored, which would return an
        # unrelated lookup type. Verified explicitly below before anything is written to it.
        r = c.post("/api/v1/mdl/lookup-types/search",
                   {"filters": [{"field": "key", "operator": "EQUALS",
                                 "value": "ACCOUNTING_EVENT_TYPE"}],
                    "page": 0, "size": 5})
        content = (data_of(r) or {}).get("content") or []
        content = [t for t in content if t.get("key") == "ACCOUNTING_EVENT_TYPE"]
        if not content:
            PRECONDITION_FAILURES.append(
                "ACCOUNTING_EVENT_TYPE lookup type not found via MDL search — "
                "event-rule and from-event suites cannot run")
            return False, "lookup type ACCOUNTING_EVENT_TYPE not found", snippet(r)
        type_id = content[0].get("lookupTypePk") or content[0].get("id")
        ctx["event_type_lookup_id"] = type_id
        code = f"SALES_INVOICE_{RUN_ID}"
        cr = c.post(f"/api/v1/mdl/lookup-types/{type_id}/values",
                    {"code": code, "nameAr": "فاتورة مبيعات", "nameEn": "Sales invoice",
                     "sortOrder": 1})
        if cr.status_code in (200, 201):
            vid = field_of(cr, "lookupValuePk") or field_of(cr, "id")
            created["MdlLookupValue"].append(vid)
            ctx["event_type_code"] = code
            return True, f"seeded ACCOUNTING_EVENT_TYPE value {code} (id={vid})", snippet(cr)
        PRECONDITION_FAILURES.append(
            f"could not seed ACCOUNTING_EVENT_TYPE value: HTTP {cr.status_code} {err_code(cr)}")
        return False, f"HTTP {cr.status_code} {err_code(cr)}", snippet(cr)

    run("precondition — seed a host-specific ACCOUNTING_EVENT_TYPE value (V26 documented step)",
        seed_event_type)

    # Stage E observation — an UNKNOWN filter field on a search body. An unknown SORT field
    # is rejected with FIN-400-INVALID-SORT (TC-FIN-064); no artifact states what an unknown
    # FILTER field must do, so this is recorded, never asserted.
