class APIClient:
    def __init__(self, base_url: str = BASE_URL):
        self.base_url = base_url
        self.token: Optional[str] = None
        self.session = requests.Session()

    def _headers(self, token: Optional[str] = None, lang: Optional[str] = None) -> dict:
        h = {"Content-Type": "application/json"}
        tok = token if token is not None else self.token
        if tok:
            h["Authorization"] = f"Bearer {tok}"
        if lang:
            h["Accept-Language"] = lang
        return h

    def _make(self, method, path, json_body=None, params=None, token=None,
              lang=None, timeout=30):
        return self.session.request(
            method, f"{self.base_url}{path}", json=json_body, params=params,
            headers=self._headers(token, lang), timeout=timeout,
        )

    def get(self, path, params=None, token=None, lang=None):
        return self._make("GET", path, params=params, token=token, lang=lang)

    def post(self, path, json_body=None, token=None, lang=None):
        return self._make("POST", path, json_body=json_body, token=token, lang=lang)

    def put(self, path, json_body=None, token=None, lang=None):
        return self._make("PUT", path, json_body=json_body, token=token, lang=lang)

    def patch(self, path, json_body=None, token=None, lang=None):
        return self._make("PATCH", path, json_body=json_body, token=token, lang=lang)

    def delete(self, path, token=None):
        return self._make("DELETE", path, token=token)

    def login(self, username: str, password: str) -> Optional[str]:
        r = self.post("/api/v1/sec/auth/login", {"username": username, "password": password})
        if r.status_code == 200:
            return ((r.json().get("data")) or {}).get("accessToken")
        return None


def data_of(resp) -> Any:
    try:
        return resp.json().get("data")
    except Exception:  # noqa: BLE001
        return None


def field_of(resp, key) -> Any:
    d = data_of(resp)
    return d.get(key) if isinstance(d, dict) else None


def err_code(resp) -> Optional[str]:
    try:
        return (resp.json().get("error") or {}).get("code")
    except Exception:  # noqa: BLE001
        return None


def snippet(resp, limit: int = 300) -> str:
    try:
        return json.dumps(resp.json(), ensure_ascii=False)[:limit]
    except Exception:  # noqa: BLE001
        return (resp.text or "")[:limit]


def expect_status(resp, want: int, what: str):
    return (resp.status_code == want,
            f"{what}: HTTP {resp.status_code} (want {want})", snippet(resp))


def expect_error(resp, want_status: int, want_code: str, what: str):
    got = err_code(resp)
    ok = resp.status_code == want_status and got == want_code
    return (ok,
            f"{what}: HTTP {resp.status_code}/{got} (want {want_status}/{want_code})",
            snippet(resp))


