def write_report(path: str):
    total_p = sum(s.passed_count for s in SUITES)
    total_f = sum(s.failed_count for s in SUITES)
    lines = [
        "# FIN — api-verify problems report",
        "",
        f"Generated: {date.today().isoformat()} · RUN_ID `{RUN_ID}` · tier **Full** "
        f"(api-docs + test-execution-manifest present)",
        f"Target: `{BASE_URL}` (Dev/Test — localhost, per api-verify-config.md §4.1)",
        "",
        f"**{total_p} passed · {total_f} failed** across {len(SUITES)} suites · "
        f"{len(OBSERVATIONS)} observation(s), which never affect the totals.",
        "",
        "## Suites",
        "",
        "| Suite | Passed | Failed |",
        "|---|---|---|",
    ]
    for s in SUITES:
        lines.append(f"| {s.entity} | {s.passed_count} | {s.failed_count} |")

    lines += ["", "## Failures", ""]
    fails = [(s, r) for s in SUITES for r in s.results if not r.passed]
    if not fails:
        lines.append("_None._")
    else:
        lines.append("| Suite | Test | Detail | Response |")
        lines.append("|---|---|---|---|")
        for s, r in fails:
            det = r.detail.replace("|", "\\|")[:300]
            snip = (r.response_snippet or "").replace("|", "\\|")[:200]
            lines.append(f"| {s.entity} | {r.name} | {det} | `{snip}` |")

    lines += ["", "## Preconditions (stage A0)", ""]
    lines += ([f"- {p}" for p in PRECONDITION_FAILURES] or ["_All preconditions satisfied._"])

    lines += ["", "## Observations (stage E — not pass/fail)", ""]
    lines += ([f"- **{o.name}** — {o.detail}" for o in OBSERVATIONS] or ["_None._"])

    lines += ["", "## Surviving records", ""]
    lines += ([f"- {n}" for n in LEFT_BEHIND] or ["_None._"])

    lines += ["", "### Permanent residue (reference tables other modules' rules read)", ""]
    lines += ([f"- {n}" for n in PERMANENT_RESIDUE] or ["_None._"])

    lines += [
        "", "## Privileges",
        "",
        "No permission grant was created or revoked by this run. The bootstrap `admin` "
        "holds SYS_ADMIN, which V24/V25/V30 already grant the FIN permission set to, so "
        "stage I was skipped entirely and no grant journal was written. No standing "
        "privilege was left behind.",
        "",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\nReport written: {path}")


