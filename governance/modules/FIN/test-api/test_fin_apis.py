def test_fiscal_year(c: APIClient):
    """Covers: API-FIN-023 (create) ; TC-FIN-031, 080, 081"""
    start_suite("FiscalYear")

    def create():
        # FiscalYear has no delete or deactivate endpoint, so years from earlier runs
        # persist forever and the code is unique. Walk forward until a free pair of years
        # is found rather than failing the whole suite on a collision.
        global FY_YEAR
        r = None
        for candidate in range(FY_YEAR, FY_YEAR + 40, 2):
            r = c.post("/api/v1/fin/fiscal-years",
                       {"code": str(candidate),
                        "startDate": f"{candidate}-01-01", "endDate": f"{candidate}-12-31",
                        "periodCount": 12})
            if err_code(r) != "FIN-409-YEAR-DUP":
                FY_YEAR = candidate
                break
        if r.status_code in (200, 201):
            ctx["fiscal_year_id"] = field_of(r, "fiscalYearPk")
            created["FiscalYear"].append(ctx["fiscal_year_id"])
            periods = field_of(r, "periods") or []
            ctx["periods"] = periods
            return (len(periods) == 12,
                    f"HTTP {r.status_code}, id={ctx['fiscal_year_id']}, "
                    f"{len(periods)} period(s) generated (want 12)", snippet(r))
        return False, f"HTTP {r.status_code} {err_code(r)}", snippet(r)

    run("TC-FIN-031 — create a fiscal year with its periods (API-FIN-023)", create)

    def periods_are_calendar_months():
        ps = ctx.get("periods") or []
        if len(ps) != 12:
            return False, f"{len(ps)} periods, cannot check month alignment", ""
        ok = all(p.get("startDate", "").endswith("-01") for p in ps)
        return (ok, f"12 periods; all start on day 1 = {ok}",
                ",".join(p.get("startDate", "") for p in ps[:3]))

    run("TC-FIN-081 — twelve periods are calendar months", periods_are_calendar_months)

    def create_second_year():
        """A REAL second fiscal year, so TC-FIN-049 can submit a period that exists but
        belongs to another year — an unknown id would only ever raise FIN-404-YEAR."""
        r = None
        for y2 in range(FY_YEAR + 1, FY_YEAR + 40):
            r = c.post("/api/v1/fin/fiscal-years",
                       {"code": str(y2), "startDate": f"{y2}-01-01", "endDate": f"{y2}-12-31",
                        "periodCount": 12})
            if err_code(r) != "FIN-409-YEAR-DUP":
                break
        if r.status_code in (200, 201):
            ctx["fiscal_year2_id"] = field_of(r, "fiscalYearPk")
            created["FiscalYear"].append(ctx["fiscal_year2_id"])
            created["FiscalPeriod"].extend(
                p.get("fiscalPeriodPk") for p in (field_of(r, "periods") or []))
        return (r.status_code in (200, 201),
                f"HTTP {r.status_code}, id={ctx.get('fiscal_year2_id')}", snippet(r))

    run("setup — a second real fiscal year (for RULE-FIN-017's cross-year branch)",
        create_second_year)

    def ensure_year_covering_today():
        """API-FIN-017 resolves its posting period from LocalDate.now()
        (AllocationRuleService.java:190-191), so a period containing TODAY must exist or the
        run can only ever raise FIN-404-PERIOD. This is a DB precondition of the environment,
        not a property of the rule under test."""
        today = date.today()
        r = c.post("/api/v1/fin/fiscal-years",
                   {"code": str(today.year), "startDate": f"{today.year}-01-01",
                    "endDate": f"{today.year}-12-31", "periodCount": 12})
        if r.status_code in (200, 201):
            ctx["current_year_id"] = field_of(r, "fiscalYearPk")
            created["FiscalYear"].append(ctx["current_year_id"])
            created["FiscalPeriod"].extend(
                p.get("fiscalPeriodPk") for p in (field_of(r, "periods") or []))
            return True, f"created fiscal year {today.year} covering today", snippet(r)
        if err_code(r) == "FIN-409-YEAR-DUP":
            return True, f"fiscal year {today.year} already exists — reused", snippet(r)
        PRECONDITION_FAILURES.append(
            f"no fiscal period covers today ({today}); API-FIN-017 cannot resolve a period")
        return False, f"HTTP {r.status_code} {err_code(r)}", snippet(r)

    run("precondition — a fiscal year covering TODAY (required by API-FIN-017's run-date "
        "period resolution)", ensure_year_covering_today)

    run("TC-FIN-080 — reject a duplicate fiscal year code (FIN-409-YEAR-DUP)",
        lambda: expect_error(
            c.post("/api/v1/fin/fiscal-years",
                   {"code": str(FY_YEAR), "startDate": f"{FY_YEAR}-01-01",
                    "endDate": f"{FY_YEAR}-12-31", "periodCount": 12}),
            409, "FIN-409-YEAR-DUP", "duplicate fiscal year code"))



