    # ── TC-BE-CU-004 — missing configValue -> 400 VALIDATION_ERROR / RULE-CU-002 ────
    # The governed code ERR-0002 `APP_CONFIGURATION_FIELDS_REQUIRED` is UNREACHABLE over HTTP,
    # and deliberately so: ConfigurationCreateRequest.configValue carries @NotBlank, so the
    # request is refused at the controller boundary by Spring bean validation before
    # AppConfigurationDomain.create() — the throw site of ERR-0002 — is ever entered. The
    # platform's documented mechanism for that refusal is GlobalExceptionHandler
    # .handleValidation: HTTP 400, wire code VALIDATION_ERROR, and a per-field `fieldErrors`
    # entry, which preserves detail (WHICH field, and every failing field at once) that the
    # single generic domain code cannot carry. Asserting the field name keeps RULE-CU-002
    # proven: configValue is still mandatory, and the refusal still names it.
    run("TC-BE-CU-004 — create without configValue rejected -> 400 VALIDATION_ERROR naming "
        "`configValue` (RULE-CU-002; ERR-0002 APP_CONFIGURATION_FIELDS_REQUIRED is "
        "structurally unreachable — @NotBlank refuses first)",
        lambda: expect_validation_field(
            c.post(BASE, {"configKey": f"MISSING_VALUE_{RUN_ID}"}),
            "configValue", "missing configValue"))

    # Evidence for the TC-BE-CU-004 classification: the blank-string variant of the same
    # RULE-CU-002 violation is rejected by the same generic code, i.e. the domain guard that
    # throws APP_CONFIGURATION_FIELDS_REQUIRED is not reachable through the HTTP surface.
    def blank_value_variant():
        r = c.post(BASE, {"configKey": f"BLANK_VALUE_{RUN_ID}", "configValue": "   "})
        return (True,
                f"blank (whitespace) configValue -> HTTP {r.status_code} ({err_code(r)}) — "
                f"same generic code as the omitted-field case", snippet(r))

    run_observation("stage E — RULE-CU-002 violated with a blank configValue rather than an "
                    "omitted one", blank_value_variant)

    # ── TC-BE-CU-005 — update keeps key (RULE-CU-003 happy), API-CU-003 ─────────
    def update_keeps_key():
        r = c.put(f"{BASE}/{main_key}", {"configValue": "smtp2.example.com"})
        d = data_of(r) or {}
        ok = (r.status_code == 200
              and d.get("configValue") == "smtp2.example.com"
              and d.get("configKey") == main_key)
        return (ok,
                f"HTTP {r.status_code}; configKey={d.get('configKey')} (want unchanged "
                f"{main_key}); configValue={d.get('configValue')}", snippet(r))

    run("TC-BE-CU-005 — update configValue leaves configKey unchanged (RULE-CU-003 happy)",
        update_keeps_key)

    # ── TC-BE-CU-008 — update (happy), updatedAt refreshed by AuditEntityListener ─
    # Split into two independent claims, because they do not hold together here:
    #   (a) the PERSISTED row's updatedAt is refreshed  — the plan's stated intent;
    #   (b) the PUT RESPONSE BODY carries that refreshed value — what a client sees.
    def update_persists_refreshed_audit():
        before = data_of(c.get(f"{BASE}/{main_key}")) or {}
        time.sleep(1.1)
        r = c.put(f"{BASE}/{main_key}", {"configValue": EX_VALUE, "notes": EX_NOTES})
        ctx["put_response_updated_at"] = (data_of(r) or {}).get("updatedAt")
        ctx["put_before_updated_at"] = before.get("updatedAt")
        time.sleep(0.2)
        after = data_of(c.get(f"{BASE}/{main_key}")) or {}
        ctx["put_persisted_updated_at"] = after.get("updatedAt")
        ok = (r.status_code == 200
              and after.get("updatedAt") is not None
              and after.get("updatedAt") != before.get("updatedAt"))
        return (ok,
                f"HTTP {r.status_code}; persisted updatedAt {before.get('updatedAt')} -> "
                f"{after.get('updatedAt')} (read back via GET); updatedBy="
                f"{after.get('updatedBy')}", snippet(r))

    run("TC-BE-CU-008 — update configuration (API-CU-003; the persisted updatedAt is "
        "refreshed by AuditEntityListener)", update_persists_refreshed_audit)

    def update_response_carries_refreshed_audit():
        resp_val = ctx.get("put_response_updated_at")
        persisted = ctx.get("put_persisted_updated_at")
        before = ctx.get("put_before_updated_at")
        ok = resp_val is not None and resp_val == persisted
        return (ok,
                f"PUT response updatedAt={resp_val}; row's actual updatedAt={persisted}; "
                f"value before this update={before} — the response body returns the "
                f"PRE-update timestamp (off by one update)", "")

    run("TC-BE-CU-008 (response body) — the PUT response reports the same updatedAt the row "
        "actually holds (documented ConfigurationResponse.updatedAt)",
        update_response_carries_refreshed_audit)

    # ── TC-BE-CU-006 — configKey immutability (RULE-CU-003), enforced STRUCTURALLY ──
    # The governed code ERR-0003 `APP_CONFIGURATION_KEY_IMMUTABLE` is UNREACHABLE, and
    # CuErrorCodes says so itself: it is "registered for catalog completeness; unused by any
    # throw site because enforcement is structural — configKey is excluded from
