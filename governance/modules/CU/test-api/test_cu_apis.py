def preflight(c: APIClient):
    """Stage A0 — verify every externally-owned value the payloads reference.

    CU's payloads reference NONE: ConfigurationCreateRequest carries only configKey,
    configValue and notes — three free-form strings, no FK, no lookup key, no owner-module
    code, no registry code, and the manifest's DEPENDENCY ORDER confirms 'no parent, no XM
    dependency'. So there is nothing externally owned to precondition-check here; what is
    checked instead is that the module's own surface is reachable and authenticated, and
    that the keys this run is about to create are genuinely free.
    """
    start_suite("PREFLIGHT (stage A0)")

    def search_reachable():
        r = c.post(f"{BASE}/search", {"page": 0, "size": 20})
        if r.status_code != 200:
            PRECONDITION_FAILURES.append(
                f"POST {BASE}/search returned HTTP {r.status_code} ({err_code(r)}) for the "
                f"authenticated bootstrap account — the CU suite cannot run")
        d = data_of(r) or {}
        return (r.status_code == 200,
                f"HTTP {r.status_code}; totalElements={d.get('totalElements')}", snippet(r))

    run("precondition — CU search surface reachable and authorised for the run account",
        search_reachable)

    def keys_free():
        taken = []
        for k in (KEY_MAIN, KEY_SECOND, KEY_INJECTION, KEY_ABSENT):
            r = c.get(f"{BASE}/{k}")
            if r.status_code == 200:
                taken.append(k)
        if taken:
            PRECONDITION_FAILURES.append(
                f"run-scoped keys already exist: {taken} — RUN_ID {RUN_ID} collided")
        return (not taken,
                f"run-scoped keys free: {not taken} (taken={taken or 'none'})", "")

    run("precondition — this run's RUN_ID-scoped configKeys are free (no collision with a "
        "sibling run)", keys_free)

    # Documented pagination envelope (index.md "Pagination Envelope"). Asserted on field
    # presence only — never on a global row count, since NOTIF/FILE runs share this database.
    def paging_envelope():
        r = c.post(f"{BASE}/search", {"page": 0, "size": 20})
        d = data_of(r) or {}
        documented = ["totalPages", "totalElements", "numberOfElements", "first", "last",
                      "pageable", "sort", "size", "number", "empty"]
        missing = [f for f in documented if f not in d]
        extra_content = "content" in d   # index.md's envelope table omits `content`
        return (r.status_code == 200 and not missing,
                f"documented page fields missing={missing or 'none'}; "
                f"content present={extra_content}", snippet(r))

    run("precondition — page envelope carries every field index.md documents", paging_envelope)


