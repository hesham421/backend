def preflight(c: APIClient):
    """Every externally-owned value the payloads reference is verified present and active
    before the suites that need it. Order is grants -> preconditions -> suites; this run
    needs no grant (see grants())."""
    start_suite("PREFLIGHT (stage A0)")

    def channel_lov():
        r = c.get(f"/api/v1/notifications/lookups/{LOOKUP_CHANNEL}")
        vals = data_of(r) or []
        codes = [v.get("code") for v in vals] if isinstance(vals, list) else []
        ctx["channel_codes"] = codes
        missing = [x for x in (CHANNEL_TYPE_EMAIL, CHANNEL_TYPE_ENABLED) if x not in codes]
        if missing:
            PRECONDITION_FAILURES.append(
                f"{LOOKUP_CHANNEL}: missing active value(s) {missing} — the dispatch api-docs "
                f"example channelHint ['EMAIL','SMS'] references them")
        return (r.status_code == 200 and not missing,
                f"{LOOKUP_CHANNEL}: {len(codes)} active value(s); missing={missing or 'none'}",
                ",".join(codes))

    run(f"MDL-owned lookup '{LOOKUP_CHANNEL}' resolves via NOTIF (XM: MdlLookupApi)", channel_lov)

    def status_lov():
        r = c.get(f"/api/v1/notifications/lookups/{LOOKUP_STATUS}")
        vals = data_of(r) or []
        codes = [v.get("code") for v in vals] if isinstance(vals, list) else []
        ctx["status_codes"] = codes
        # The four statuses the api-docs' own notificationStatusId description and the test plan
        # name: PENDING (initial), SENT, FAILED, CHANNEL_DISABLED.
        wanted = ["PENDING", "SENT", "FAILED", "CHANNEL_DISABLED"]
        missing = [x for x in wanted if x not in codes]
        if missing:
            PRECONDITION_FAILURES.append(
                f"{LOOKUP_STATUS}: missing active value(s) {missing} — dispatch writes them as "
                f"notificationStatusId")
        return (r.status_code == 200 and not missing,
                f"{LOOKUP_STATUS}: {len(codes)} active value(s); missing={missing or 'none'}",
                ",".join(codes))

    run(f"MDL-owned lookup '{LOOKUP_STATUS}' resolves via NOTIF (XM: MdlLookupApi)", status_lov)

    def recipient():
        """recipientId is an externally-owned SEC UserAccount id. The api-docs example is 42;
        NOTIF documents no endpoint to verify it, so it is resolved through SEC's own documented
        search endpoint instead of being trusted as a literal (SKILL.md §3-A0)."""
        r = c.post("/api/v1/sec/users/search", {"page": 0, "size": 200})
        content = (data_of(r) or {}).get("content") or []
        active = [u for u in content if u.get("isActiveFl") is True]
        inactive = [u for u in content if u.get("isActiveFl") is False]
        if active:
            ctx["recipient_id"] = active[0].get("userPk")
        if inactive:
            ctx["inactive_recipient_id"] = inactive[0].get("userPk")
        if not active:
            PRECONDITION_FAILURES.append(
                "no ACTIVE SEC user account found — dispatch suites cannot bind a real recipientId")
        return (bool(active),
                f"recipientId resolved from SEC: active={ctx.get('recipient_id')}, "
                f"inactive={ctx.get('inactive_recipient_id')} "
                f"(api-docs example 42 not used as a literal)",
                snippet(r, 120))

    run("recipientId (SEC UserAccount, XM-NOTIF-001) resolved and verified active", recipient)

    def email_channel_state():
        """The EMAIL channel config is pre-existing seed data (id 1) this run must not mutate.
        Its enabled state decides what an EMAIL dispatch does, so it is read, never written."""
        r = c.post("/api/v1/notifications/channels/search",
                   {"filters": [{"field": "channelTypeId", "operator": "EQUALS",
                                 "value": CHANNEL_TYPE_EMAIL}], "page": 0, "size": 50})
        content = (data_of(r) or {}).get("content") or []
        mine = [x for x in content if x.get("channelTypeId") == CHANNEL_TYPE_EMAIL]
        if mine:
            ctx["email_channel_enabled"] = mine[0].get("isEnabledFl")
            ctx["email_channel_id"] = mine[0].get("id")
        return (r.status_code == 200,
                f"pre-existing EMAIL channel config: id={ctx.get('email_channel_id')}, "
                f"isEnabledFl={ctx.get('email_channel_enabled')} (read-only, never mutated here)",
                snippet(r, 200))

    run("pre-existing EMAIL channel config read (not mutated)", email_channel_state)


