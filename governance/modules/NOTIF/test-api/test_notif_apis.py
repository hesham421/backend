def cleanup(c: APIClient):
    """Reverse of the manifest's DEPENDENCY ORDER (log -> channel -> template).
    NOTIF documents NO hard-delete endpoint for any entity, so every call below is the
    documented soft deactivate/disable and the rows survive — listed individually in the
    report, never summarised as 'cleaned up'."""
    print("\n=== CLEANUP (reverse dependency order) ===")

    log_ids = [i for i in created["NotificationLog"] if i]
    if log_ids:
        LEFT_BEHIND.append(
            f"NotificationLog: {len(log_ids)} row(s) {log_ids} — the ENTITY CRUD CHECKLIST marks "
            f"NOTIF_LOG a read-only screen with no delete and no deactivate endpoint, so they "
            f"survive. All carry referenceType='{REFERENCE_TYPE}'. "
            f"Cleanup SQL: DELETE FROM NOTIF_LOG WHERE REFERENCE_TYPE = '{REFERENCE_TYPE}';")

    for cid in [i for i in created["NotificationChannelConfig"] if i]:
        try:
            r = c.delete(f"/api/v1/notifications/channels/{cid}")
            print(f"  disable channel {cid}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  disable channel {cid} FAILED: {e}")
    if [i for i in created["NotificationChannelConfig"] if i]:
        PERMANENT_RESIDUE.append(
            f"NOTIF_CHANNEL_CONFIG rows {[i for i in created['NotificationChannelConfig'] if i]} "
            f"(channelTypeId "
            f"{[CHANNEL_TYPE_ENABLED, ctx.get('undocumented_channel_code')]}) — disabled via the "
            f"documented DELETE, but the rows persist and CHANNEL_TYPE_ID is UNIQUE, so a later "
            f"run creating the same channel type gets 409. This table is read by dispatch for "
            f"every module that sends a notification. "
            f"Cleanup SQL: DELETE FROM NOTIF_CHANNEL_CONFIG WHERE CHANNEL_TYPE_ID IN "
            f"('{CHANNEL_TYPE_ENABLED}', '{ctx.get('undocumented_channel_code')}');")

    for tid in [i for i in created["NotificationTemplate"] if i]:
        try:
            r = c.delete(f"/api/v1/notifications/templates/{tid}")
            print(f"  deactivate template {tid}: {r.status_code}")
        except Exception as e:  # noqa: BLE001
            print(f"  deactivate template {tid} FAILED: {e}")
    if [i for i in created["NotificationTemplate"] if i]:
        LEFT_BEHIND.append(
            f"NotificationTemplate: {[i for i in created['NotificationTemplate'] if i]} — "
            f"deactivated (soft, isActiveFl=false); NOTIF documents no hard delete. Codes are "
            f"RUN_ID-suffixed ('%_{RUN_ID}'). "
            f"Cleanup SQL: DELETE FROM NOTIF_TEMPLATE WHERE TEMPLATE_CODE LIKE '%\\_{RUN_ID}';")


