    run("TC-BE-NOTIF-014 — search finds this run's template", search)

    # Stage C — RULE-NOTIF-006 / ERR-0002 / TC-BE-NOTIF-009 (template half), 409.
    run("TC-BE-NOTIF-009 — duplicate templateCode -> 409 NOTIF_TEMPLATE_CODE_DUPLICATE",
        lambda: expect_error(c.post("/api/v1/notifications/templates", body),
                             409, "NOTIF_TEMPLATE_CODE_DUPLICATE", "duplicate code"))

    # Stage C — RULE-NOTIF-004 / TC-BE-NOTIF-006, 400, on CREATE and on UPDATE.
