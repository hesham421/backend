def test_access_token_and_download(c: APIClient):
    """Covers: API-FILE-002 (issue token), API-FILE-003 (download) ;
    Negative: RULE-FILE-003 / FILE_ACCESS_TOKEN_INVALID / TC-BE-FILE-006 / 401
    TC-BE-FILE-005, 006, 014, 015"""
    start_suite("FileDocument — access token & download")

    fid = ctx.get("file_id")
    if not fid:
        blocked("TC-BE-FILE-005/006/014/015", "no uploaded file")
        return

    def issue():
        r = c.post(f"/api/v1/files/{fid}/access-token")
        d = data_of(r) or {}
        ctx["dl_token"] = d.get("accessToken")
        ok = r.status_code == 200 and bool(d.get("accessToken")) and bool(d.get("expiresAt"))
        return (ok,
                f"HTTP {r.status_code}, accessToken present={bool(d.get('accessToken'))}, "
                f"expiresAt={d.get('expiresAt')}", snippet(r))

    run("TC-BE-FILE-014 — issue a single-use access token -> 200 {accessToken, expiresAt} "
        "(API-FILE-002)", issue)

    tok = ctx.get("dl_token")
    if not tok:
        blocked("TC-BE-FILE-005/015/006", "no access token issued")
    else:
        def download_once():
            r = c.download(tok)
            length = len(r.content)
            disp = r.headers.get("Content-Disposition", "")
            # Compared against the fileSize the server itself recorded at upload
            # (api-docs FileMetadataResponse.fileSize), not against a local constant.
            want = ctx.get("file_size")
            ok = (r.status_code == 200 and length == want
                  and "attachment" in disp.lower())
            return (ok,
                    f"HTTP {r.status_code}, body={length} bytes (server-recorded "
                    f"fileSize={want}), Content-Type={r.headers.get('Content-Type')}, "
                    f"Content-Disposition={disp[:60]!r}", f"<{length} bytes>")

        run("TC-BE-FILE-005/015 — download with a fresh token -> 200 byte stream, "
            "size matches the upload (API-FILE-003)", download_once)

        def download_reused():
            r = c.download(tok)
            return expect_error(r, 401, "FILE_ACCESS_TOKEN_INVALID",
                                "the same token used a second time")

        run("TC-BE-FILE-006/015 — the SAME token reused is refused "
            "(RULE-FILE-003 / FILE_ACCESS_TOKEN_INVALID / 401) — single-use proven end-to-end",
            download_reused)

