def preflight(c: APIClient):
    """Stage A0 — the externally-owned values this run's payloads and assertions
    reference are the LOV codes FILE fronts from MDL (XM edge: FileLookupService ->
    MdlLookupApi). Order is grants -> preconditions -> suites; this run needs no grant."""
    start_suite("PREFLIGHT (stage A0)")

    def check(key, wanted):
        def _fn():
            r = c.get(f"/api/v1/files/lookups/{key}")
            vals = data_of(r) or []
            codes = [v.get("code") for v in vals] if isinstance(vals, list) else []
            ctx[f"lookup_{key}"] = codes
            missing = [w for w in wanted if w not in codes]
            if missing or r.status_code != 200:
                PRECONDITION_FAILURES.append(
                    f"{key}: HTTP {r.status_code}, missing active value(s) {missing} — "
                    f"FILE's own api-docs / lifecycle assertions reference them")
            return (r.status_code == 200 and not missing,
                    f"{key}: HTTP {r.status_code}, {len(codes)} active value(s); "
                    f"missing={missing or 'none'}",
                    ",".join(codes))
        return _fn

    # LOV-FILE-001 buckets referenced by the upload response assertions (api-docs
    # FileMetadataResponse examples: fileTypeId=DOCUMENT, and IMAGE for the PNG case).
    run(f"XM — MDL-owned lookup '{LOOKUP_FILE_TYPE}' resolves through FILE (API-FILE-008)",
        check(LOOKUP_FILE_TYPE, ["DOCUMENT", "IMAGE"]))
    # LOV-FILE-002 statuses asserted by the lifecycle suite.
    run(f"XM — MDL-owned lookup '{LOOKUP_FILE_STATUS}' resolves through FILE (API-FILE-008)",
        check(LOOKUP_FILE_STATUS, ["ACTIVE", "ARCHIVED", "DELETED"]))

    # The owner triple is a plain polymorphic string set in FILE's own schema (no FK to
    # any registry), so there is no registry row to precondition-check. Recorded, not asserted.
    def owner_triple_unvalidated():
        r = c.get("/api/v1/files", params={"ownerId": OWNER_ID, "ownerType": OWNER_TYPE,
                                           "moduleCode": MODULE_CODE, "page": 0, "size": 5})
        total = (data_of(r) or {}).get("totalElements")
        return (True,
                f"owner triple ({OWNER_ID}/{OWNER_TYPE}/{MODULE_CODE}) readable: HTTP "
                f"{r.status_code}, totalElements={total} — moduleCode is an unconstrained "
                f"string here (no FK / registry validation on upload), so it is not a "
                f"precondition row", snippet(r))

    run_observation("stage A0 note — moduleCode/ownerType are unvalidated free strings",
                    owner_triple_unvalidated)


