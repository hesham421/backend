def png_bytes(payload_len: int = 0) -> bytes:
    """A real 1x1 PNG (valid magic bytes, so server-side content sniffing detects
    image/png), optionally padded with a trailing ancillary chunk to reach a size."""

    def chunk(ctype: bytes, body: bytes) -> bytes:
        return (len(body).to_bytes(4, "big") + ctype + body
                + zlib.crc32(ctype + body).to_bytes(4, "big"))

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = chunk(b"IHDR", (1).to_bytes(4, "big") + (1).to_bytes(4, "big")
                 + bytes([8, 2, 0, 0, 0]))
    idat = chunk(b"IDAT", zlib.compress(b"\x00\xff\xff\xff"))
    iend = chunk(b"IEND", b"")
    out = sig + ihdr + idat + iend
    if payload_len > len(out):
        pad = payload_len - len(out)
        # tEXt is an ancillary chunk: padding does not invalidate the PNG.
        out = sig + ihdr + chunk(b"tEXt", b"pad\x00" + b"A" * max(pad - 16, 0)) + idat + iend
    return out


def exe_bytes(size: int = 4096) -> bytes:
    """A DOS/PE executable header — TC-BE-FILE-004's ".exe disguised as image"."""
    return b"MZ\x90\x00\x03\x00\x00\x00\x04\x00\x00\x00\xff\xff\x00\x00" + b"\x00" * (size - 16)


def text_bytes(size: int) -> bytes:
    """Exactly `size` bytes of plain text — the length is asserted against the
    server-recorded fileSize, so it must be exact, not approximate."""
    seed = ("api-verify FILE run " + RUN_ID + " ").encode()
    return (seed * (size // len(seed) + 1))[:size]


